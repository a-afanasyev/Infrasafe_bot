"""Кириллица → узбекская латиница для сопоставления по тексту.

Детерминированный транслит (х→x, ж→j, ў→o', қ→q, ғ→g', ҳ→h) — НЕ полагаемся
на LLM ни для адресов (`address_hint` берётся дословно из сообщения), ни для
ключевых слов категорий. Одна таблица на оба потребителя: адресный матчинг
(`handlers/group_intake._hint_variants`) и `category_keywords`.

Узбекские буквы ў/қ/ғ/ҳ обязательны: без них «оқмаяпти» не становится
«oqmayapti», и кириллические сообщения из групп мимо словаря.
"""

CYR_TO_LAT = str.maketrans({
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "j", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "x", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "i", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    # узбекская кириллица
    "ў": "o'", "қ": "q", "ғ": "g'", "ҳ": "h",
})


def translit(text: str) -> str:
    """Нижний регистр + транслит; латиница и цифры проходят как есть."""
    return (text or "").lower().translate(CYR_TO_LAT)
